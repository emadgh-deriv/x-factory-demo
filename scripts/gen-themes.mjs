// Generates app/theme/tokens.css: 4 seed themes × light/dark, MD3 SchemeFidelity.
// Run: node scripts/gen-themes.mjs. Do not hand-edit the output.
import { writeFileSync } from "node:fs";
import { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors as C, SchemeFidelity } from "@material/material-color-utilities";

const SEEDS = { blue: "#1565C0", green: "#2E7D32", gold: "#B8860B", red: "#C62828" };
const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondaryContainer", "onSecondaryContainer",
  "surface", "onSurface", "onSurfaceVariant",
  "surfaceContainerLow", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "outline", "outlineVariant", "error", "errorContainer", "onErrorContainer",
];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

function block(selector, seed, dark, indent = "") {
  const s = new SchemeFidelity(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const lines = ROLES.map((r) => `${indent}  --md-sys-color-${kebab(r)}: ${hexFromArgb(C[r].getArgb(s))};`);
  lines.push(`${indent}  color-scheme: ${dark ? "dark" : "light"};`);
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`;
}

const others = Object.keys(SEEDS).filter((t) => t !== "blue");
const out = [
  "/* GENERATED by scripts/gen-themes.mjs (SchemeFidelity, material-color-utilities 0.3.0). Do not edit. */",
  "/* Stadium Blue light is the default. With no data-mode the device's prefers-color-scheme picks the mode. */",
  ":root {\n  --md-ref-typeface-brand: var(--font-roboto), Roboto, system-ui, sans-serif;\n  --md-ref-typeface-plain: var(--font-roboto), Roboto, system-ui, sans-serif;\n}",
  block(":root", SEEDS.blue, false),
  ...others.map((t) => block(`:root[data-theme="${t}"]`, SEEDS[t], false)),
  block(`:root[data-mode="dark"]`, SEEDS.blue, true),
  ...others.map((t) => block(`:root[data-theme="${t}"][data-mode="dark"]`, SEEDS[t], true)),
  "@media (prefers-color-scheme: dark) {",
  block(`:root:not([data-mode="light"])`, SEEDS.blue, true, "  "),
  ...others.map((t) => block(`:root[data-theme="${t}"]:not([data-mode="light"])`, SEEDS[t], true, "  ")),
  "}",
];
writeFileSync(new URL("../app/theme/tokens.css", import.meta.url), out.join("\n\n") + "\n");
